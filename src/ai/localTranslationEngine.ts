export class LocalTranslationEngine {
  private static translatedNodes = new Map<Node, string>();
  private static isTranslated = false;
  private static activeLanguage = 'en';

  /**
   * Translates plain text using local offline dictionaries
   */
  static translateText(text: string, targetLang: string): string {
    if (!text || text.trim() === '' || targetLang === 'en') return text;

    const dict = LOCAL_TRANSLATION_DICTIONARIES[targetLang.toLowerCase()];
    if (!dict) {
      return text;
    }

    let translated = text;

    // Sort dictionary keys by length descending to match multi-word phrases first
    const sortedKeys = Object.keys(dict).sort((a, b) => b.length - a.length);

    for (const phrase of sortedKeys) {
      const targetWord = dict[phrase];
      const regex = new RegExp(`\\b${phrase}\\b`, 'gi');
      translated = translated.replace(regex, targetWord);
    }

    return translated;
  }

  /**
   * Recursively translates visible text nodes in the DOM without breaking HTML tags,
   * scripts, code, inputs, or event bindings.
   */
  static translatePageDOM(targetLang: string, rootElement: HTMLElement = document.body): { translatedCount: number } {
    if (typeof document === 'undefined') return { translatedCount: 0 };

    if (targetLang === 'en') {
      return { translatedCount: this.restoreOriginalPage() };
    }

    this.activeLanguage = targetLang;
    let count = 0;

    const walker = document.createTreeWalker(
      rootElement,
      NodeFilter.SHOW_TEXT,
      {
        acceptNode: (node) => {
          const parent = node.parentElement;
          if (!parent) return NodeFilter.FILTER_REJECT;

          const tag = parent.tagName.toUpperCase();
          if (
            ['SCRIPT', 'STYLE', 'NOSCRIPT', 'CODE', 'PRE', 'INPUT', 'TEXTAREA'].includes(tag) ||
            parent.closest('#swde-floating-toolbar-root') ||
            parent.closest('#swde-sentence-simplifier-tooltip') ||
            parent.closest('#swde-reading-mode-root')
          ) {
            return NodeFilter.FILTER_REJECT;
          }

          const val = node.nodeValue?.trim();
          if (!val || val.length < 2) return NodeFilter.FILTER_REJECT;

          return NodeFilter.FILTER_ACCEPT;
        },
      }
    );

    let currentNode: Node | null = walker.nextNode();
    while (currentNode) {
      const original = currentNode.nodeValue || '';
      if (!this.translatedNodes.has(currentNode)) {
        this.translatedNodes.set(currentNode, original);
      }

      const translated = this.translateText(original, targetLang);
      if (translated !== original) {
        currentNode.nodeValue = translated;
        count++;
      }

      currentNode = walker.nextNode();
    }

    this.isTranslated = true;
    return { translatedCount: count };
  }

  /**
   * Restores all modified DOM text nodes to their original English strings.
   */
  static restoreOriginalPage(): number {
    let count = 0;
    this.translatedNodes.forEach((origText, node) => {
      try {
        node.nodeValue = origText;
        count++;
      } catch (_) {}
    });

    this.translatedNodes.clear();
    this.isTranslated = false;
    this.activeLanguage = 'en';
    return count;
  }

  static translateCurrentPage(targetLang: string): { translatedCount: number } {
    return this.translatePageDOM(targetLang);
  }

  static getStatus(): { isTranslated: boolean; activeLanguage: string } {
    return {
      isTranslated: this.isTranslated,
      activeLanguage: this.activeLanguage,
    };
  }
}
